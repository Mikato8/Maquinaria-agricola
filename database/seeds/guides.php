<h2>Qué significan SPN y FMI</h2>
<p>En el estándar SAE J1939, cada falla se describe con dos números:</p>
<ul>
<li><strong>SPN (Suspect Parameter Number):</strong> qué se está midiendo. Por ejemplo, SPN 100 es presión de aceite del motor; SPN 110, temperatura de refrigerante; SPN 168, voltaje de batería.</li>
